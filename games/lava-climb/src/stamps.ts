import type { DropSpec, MoveSpec } from './level.ts';

/**
 * A stamp is one handcrafted stretch of tower, 14 tiles wide and read top row first.
 *   . air        # rock       W rock with handholds       = ledge      ~ crumbling ledge
 *   > < belts    B bouncy     ^ v [ ] spikes              * gem        $ secret gem
 *   H a false wall            m moving platform           r rock hole
 * A jump climbs 3 rows, so the lowest ledge of a stamp sits at most 3 rows above the top row of the last.
 */
export interface Stamp {
  rows: string[];
  moves?: MoveSpec[];
  drops?: DropSpec[];
}

const move = (dx: number, dy: number, period: number, phase = 0): MoveSpec => ({ dx, dy, period, phase });
const drop = (period: number, phase = 0): DropSpec => ({ period, phase });

