export type StampName = keyof typeof STAMPS;

const FLIP: Record<string, string> = { '<': '>', '>': '<', '[': ']', ']': '[' };

/** The same stretch of tower, seen in a mirror. */
export function mirrored(stamp: Stamp): Stamp {
  return {
    rows: stamp.rows.map((row) => [...row].reverse().map((letter) => FLIP[letter] ?? letter).join('')),
    moves: stamp.moves?.map((spec) => ({ ...spec, dx: -spec.dx })),
    drops: stamp.drops,
  };
}
